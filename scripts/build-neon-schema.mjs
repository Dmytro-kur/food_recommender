import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const migrationsDir = path.join(repoRoot, "neon", "migrations");
const schemaPath = path.join(repoRoot, "neon", "schema.sql");

const migrationPattern = /^\d+.*\.sql$/;

async function buildSchema() {
  const migrationFiles = (await readdir(migrationsDir))
    .filter((fileName) => migrationPattern.test(fileName))
    .sort((left, right) => left.localeCompare(right));

  if (migrationFiles.length === 0) {
    throw new Error("No migration files found in neon/migrations");
  }

  const sections = await Promise.all(
    migrationFiles.map(async (fileName) => {
      const filePath = path.join(migrationsDir, fileName);
      const sql = await readFile(filePath, "utf8");

      return `-- Migration: ${fileName}\n\n${sql.trimEnd()}`;
    }),
  );

  const schema = [
    "-- Generated from neon/migrations by `npm run db:build-schema`.",
    "-- Do not edit this file by hand; edit the migration files instead.",
    "",
    ...sections,
    "",
  ].join("\n");

  await writeFile(schemaPath, schema);
}

buildSchema().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
